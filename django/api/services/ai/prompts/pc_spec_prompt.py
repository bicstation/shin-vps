# FILE:
# api/services/ai/prompts/pc_spec_prompt.py
# =========================================================

class PCSpecPrompt:

    # =====================================================
    # BUILD
    # =====================================================

    def build(
        self,
        product,
    ):

        description = (
            product.description
            or ""
        )[:2000]
        
        observation = (
                    product.observation_runtime
                    or ""
                )[:2000]

        return f"""
PC製品仕様を抽出してください。

==============================================================================
Reality
==============================================================================

MAKER:
{product.maker}

NAME:
{product.name}

MODEL:
{product.model}

PRODUCT_NO:
{product.product_no}

URL:
{product.url}

DESCRIPTION:
{description}

OBSERVATION:
{observation}

==============================================================================
Reality Rules
==============================================================================

商品名・型番・メーカー・URL を用いて、
一意に特定できるメーカー公開仕様をRealityとして採用してください。

メーカー公開仕様で確認できた内容は推測ではありません。

DESCRIPTIONよりもメーカー公開仕様を優先してください。

OBSERVATIONは公開仕様の補助情報として利用できます。

メーカー公開仕様でも確認できない項目のみ、
空文字("") または 0 を返してください。

==============================================================================
AI PC
==============================================================================

AI PC はメーカー公開仕様および公開CPUシリーズ・NPU情報から判定してください。

以下は AI PC と判定してください。

・Intel Core Ultra
・AMD Ryzen AI
・Snapdragon X

これは推測ではありません。
公開CPUシリーズによる判定です。

==============================================================================
Normalization
==============================================================================

memory_gb と storage_gb は GB の整数で返してください。

■ Memory

16GB → 16
32GB → 32
64GB → 64

■ Storage

256GB → 256
512GB → 512
1TB → 1000
2TB → 2000
4TB → 4000

TB は必ず 1000GB 換算としてください。
1024GB換算は行わないでください。

DDR5
LPDDR5X
NVMe
PCIe Gen4

などは容量ではありません。

==============================================================================
Display
==============================================================================

ノートPC・一体型PCでメーカー公開仕様に
ディスプレイ情報が存在する場合のみ抽出してください。

display_info には

・サイズ
・解像度
・リフレッシュレート

などを含めてください。

デスクトップPCでディスプレイを搭載しない場合は

"display_info": ""

==============================================================================
Output
==============================================================================

JSONのみ返してください。

{{
  "cpu_model": "",
  "gpu_model": "",
  "memory_gb": 0,
  "storage_gb": 0,
  "display_info": "",
  "is_ai_pc": false
}}
"""